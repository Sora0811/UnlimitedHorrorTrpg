# -*- coding: utf-8 -*-
"""依搬移結果重建 dTree 導航 left.htm。

策略：保留原 left.htm 的完整樹狀結構（最多 7 層），只做三件事
  1. 最上層四章 -> 三章：規則 / 資源 / 未開放
     其中「怪物圖鑑」整章掛到「規則」底下的新節點「ST幫助」
  2. 每個節點的檔案路徑換成搬移後的新路徑
  3. $$unsavedpage 分組節點改成純文字節點（href 留空）
標題一律沿用原 left.htm（已是繁體），不改字；只有章節根節點改名。
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = ROOT / "Resource"
SRC_NAV = RES / "234" / "left.htm"
PLAN = ROOT / "build" / "move-plan.json"

ADD_RE = re.compile(
    r'd\.add\(\s*(\d+)\s*,\s*(-?\d+)\s*,\s*"((?:[^"\\]|\\.)*)"\s*,\s*"((?:[^"\\]|\\.)*)"\s*\)'
)

VIRTUAL_ROOT = "無限恐怖規則"

# 原頂層章節 -> (新標題, 掛到哪個新章節, 是否另建子節點)
TOP_MAP = {
    "規則部分": ("規則",   "規則",   False),
    "資源部分": ("資源",   "資源",   False),
    "暫不開放": ("未開放", "未開放", False),
    "怪物圖鑑": ("ST幫助", "規則",   True),   # 掛在「規則」底下
}
NEW_CHAPTERS = ["規則", "資源", "未開放"]


def main():
    plan = json.loads(PLAN.read_text(encoding="utf-8"))
    newpath = {p["file"]: p["to"] for p in plan["pages"]}

    nodes = []
    for m in ADD_RE.finditer(SRC_NAV.read_text(encoding="utf-8", errors="replace")):
        nodes.append({
            "id": int(m.group(1)),
            "pid": int(m.group(2)),
            "title": m.group(3).replace('\\"', '"'),
            "file": m.group(4).replace('\\"', '"'),
        })

    by_id = {n["id"]: n for n in nodes}
    for n in nodes:
        chain, cur, guard = [], n, 0
        while cur is not None and guard < 40:
            chain.append(cur["title"])
            cur = by_id.get(cur["pid"]) if cur["pid"] != -1 else None
            guard += 1
        chain.reverse()
        if chain and chain[0] == VIRTUAL_ROOT:
            chain = chain[1:]
        n["chain"] = chain

    # 章節首頁：chain 長度 1 且是已知章節
    chapter_index = {}
    for n in nodes:
        ch = n["chain"]
        if len(ch) == 1 and ch[0] in TOP_MAP and n["file"]:
            chapter_index[ch[0]] = newpath.get(n["file"], "")

    out = []       # (new_id, new_pid, title, url)
    remap = {}
    next_id = 0

    def add(title, pid, url=""):
        nonlocal next_id
        nid = next_id
        next_id += 1
        out.append((nid, pid, title, url))
        return nid

    root = add(VIRTUAL_ROOT, -1)
    remap[0] = root
    remap[-1] = root

    # 三個新章節（帶首頁網址）
    chap_id = {}
    for name in NEW_CHAPTERS:
        chap_id[name] = add(name, root, chapter_index.get(
            {"規則": "規則部分", "資源": "資源部分", "未開放": "暫不開放"}[name], ""))

    # ST幫助：怪物圖鑑整章的落腳處，掛在「規則」下
    st_id = add("ST幫助", chap_id["規則"])

    # 原章節根節點 -> 新章節節點（不另建）
    for n in nodes:
        ch = n["chain"]
        if len(ch) == 1 and ch[0] in TOP_MAP:
            new_title, parent, is_child = TOP_MAP[ch[0]]
            if is_child:
                remap[n["id"]] = st_id
                url = newpath.get(n["file"], "") if n["file"] else ""
                if url:                      # 怪物圖鑑的總綱頁
                    add("總綱", st_id, url)
            else:
                remap[n["id"]] = chap_id[new_title]
            continue

        if not ch or ch[0] not in TOP_MAP:
            continue

        new_title, parent_ch, is_child = TOP_MAP[ch[0]]
        url = newpath.get(n["file"], "") if n["file"] else ""
        pid = st_id if is_child else remap.get(n["pid"], chap_id[parent_ch])
        remap[n["id"]] = add(n["title"], pid, url)

    # 輸出
    lines = [
        '<html>',
        '<head>',
        '    <meta charset="utf-8">',
        '    <meta name="generator" content="CHM Decoder by GridinSoft LLC   www.gridinsoft.com">',
        '    <link rel="StyleSheet" href="dtree.css" type="text/css" />',
        '    <script type="text/javascript" src="dtree.js"></script>',
        '</head>',
        '<body>',
        '<!-- Generated by CHM Decoder (http://www.gridinsoft.com) -->',
        '<div class="dtree">',
        '<p><a href="javascript: d.openAll();">open all</a> | <a href="javascript: d.closeAll();">close all</a></p>',
        '<script type="text/javascript"><!--',
        'd = new dTree("d");',
    ]
    for nid, pid, title, url in out:
        t = title.replace('"', '\\"')
        u = url.replace('"', '\\"')
        lines.append(f'd.add({nid},{pid},"{t}","{u}");')
    lines += [
        'document.write(d);',
        '//-->',
        '</script>',
        '</div>',
        '</body>',
        '</html>',
    ]

    target = RES / "left.htm"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")

    linked = sum(1 for _, _, _, u in out if u)
    print(f"已寫入 {target.relative_to(ROOT)}")
    print(f"  節點 {len(out)}（連結 {linked}，分組 {len(out) - linked}）")


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
